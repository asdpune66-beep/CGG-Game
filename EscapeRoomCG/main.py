# KEYBOARD
# ============================================================

def key_down(event):

    key = event.keysym.lower()

    movement_keys = {
        "w",
        "a",
        "s",
        "d",
        "up",
        "down",
        "left",
        "right",
    }

    if key in movement_keys:

        keys_held.add(key)
        return

    # --------------------------------------------------------
    # Transformation controls
    # Q / E : rotate player
    # Z / X : scale player down / up
    # --------------------------------------------------------

    if key == "q":
        rotate_player(-5)

    elif key == "e":
        rotate_player(5)

    elif key == "z":
        scale_player(0.95)

    elif key == "x":
        scale_player(1.05)


def key_up(event):

    key = event.keysym.lower()

    # As soon as the key is released it is removed.
    # The next movement cycle therefore produces no movement
    # for that key.
    keys_held.discard(key)


root.bind(
    "<KeyPress>",
    key_down,
)

root.bind(
    "<KeyRelease>",
    key_up,
)


# ============================================================
# SMOOTH MOVEMENT LOOP
# ==================    ==========================================

def smooth_movement():
    """
    Continuous press-and-hold movement.

    Key pressed + held:
        player keeps translating.

    Key released:
        that direction immediately becomes zero.
    """

    dx = 0.0
    dy = 0.0

    # Up.
    if (
        "w" in keys_held
        or "up" in keys_held
    ):
        dy -= MOVE_STEP

    # Down.
    if (
        "s" in keys_held
        or "down" in keys_held
    ):
        dy += MOVE_STEP

    # Left.
    if (
        "a" in keys_held
        or "left" in keys_held
    ):
        dx -= MOVE_STEP

    # Right.
    if (
        "d" in keys_held
        or "right" in keys_held
    ):
        dx += MOVE_STEP

    # Prevent diagonal movement from being faster.
    if dx != 0 and dy != 0:

        dx *= 0.70710678
        dy *= 0.70710678

    # If no movement key is held:
    # dx = 0 and dy = 0, so the player stops.
    if dx != 0 or dy != 0:

        move_player(
            dx,
            dy,
        )

    # Schedule the next movement check.
    root.after(
        MOVEMENT_INTERVAL,
        smooth_movement,
    )


