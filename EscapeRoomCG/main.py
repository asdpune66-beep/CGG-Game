def player_pixel(x, y, color=PLAYER_COLOR):

    plot(
        x,
        y,
        color,
        PLAYER_TAG,
    )


def player_line(
    x1,
    y1,
    x2,
    y2,
    color=PLAYER_COLOR,
):
    """
    DDA-based line specifically for the dynamic player layer.
    """

    dx = x2 - x1
    dy = y2 - y1

    steps = max(abs(dx), abs(dy))

    if steps == 0:
        player_pixel(
            x1,
            y1,
            color,
        )
        return

    x_inc = dx / steps
    y_inc = dy / steps

    x = x1
    y = y1

    # IMPORTANT:
    # The iteration count must be integer because smooth
    # diagonal translation produces floating-point coordinates.
    for _ in range(int(round(steps)) + 1):

        player_pixel(
            x,
            y,
            color,
        )

        x += x_inc
        y += y_inc


def player_circle(
    cx,
    cy,
    radius,
    color=PLAYER_COLOR,
):
    """
    Midpoint-circle style rendering for player detail.
    """

    x = 0
    y = radius
    p = 1 - radius

    def emit(px, py):

        points = (
            (cx + px, cy + py),
            (cx - px, cy + py),
            (cx + px, cy - py),
            (cx - px, cy - py),

            (cx + py, cy + px),
            (cx - py, cy + px),
            (cx + py, cy - px),
            (cx - py, cy - px),
        )

        for qx, qy in points:

            player_pixel(
                qx,
                qy,
                color,
            )

    emit(x, y)

    while x < y:

        x += 1

        if p < 0:

            p += 2 * x + 1

        else:

            y -= 1
            p += 2 * (x - y) + 1

        emit(x, y)


def scaling_matrix(sx, sy):
    """
    Homogeneous 2D scaling matrix:

        [ sx  0   0 ]
    S = [  0 sy   0 ]
        [  0  0   1 ]
    """
    return [
        [sx, 0, 0],
        [0, sy, 0],
        [0, 0, 1],
    ]


def rotation_matrix(angle_degrees):
    """
    Homogeneous 2D rotation matrix about the origin:

        [ cos -sin  0 ]
    R = [ sin  cos  0 ]
        [  0    0   1 ]
    """
    theta = math.radians(angle_degrees)
    c = math.cos(theta)
    s = math.sin(theta)

    return [
        [c, -s, 0],
        [s,  c, 0],
        [0,  0, 1],
    ]


def multiply_matrices(A, B):
    """Multiply two 3x3 homogeneous matrices."""
    return [
        [
            sum(A[i][k] * B[k][j] for k in range(3))
            for j in range(3)
        ]
        for i in range(3)
    ]


def apply_matrix(x, y, M):
    """Apply a 3x3 homogeneous matrix to a 2D point."""
    return (
        M[0][0] * x + M[0][1] * y + M[0][2],
        M[1][0] * x + M[1][1] * y + M[1][2],
    )


def transform_local_point(local_x, local_y, scale=1.0, angle_degrees=0.0):
    """
    Apply scaling first and rotation second to the player's
    local coordinates, then translate the result to the player's
    current world position.
    """
    S = scaling_matrix(scale, scale)
    R = rotation_matrix(angle_degrees)

    # Composite transformation: R * S
    M = multiply_matrices(R, S)

    x, y = apply_matrix(local_x, local_y, M)

    # Translation is the player's current position.
    return player_x + x, player_y + y


def draw_transformed_player_shape():
    """
    Draw the player from local coordinates.

    The same local shape is scaled and rotated before being
    translated to the player's current position.
    """

    local_points = [
        (0, -5),
        (4, 0),
        (2, 4),
        (0, 2),
        (-3, 5),
        (-4, 0),
    ]

    points = [
        transform_local_point(
            x,
            y,
            player_scale,
            player_angle,
        )
        for x, y in local_points
    ]

    # Draw transformed polygon edges using DDA.
    for i in range(len(points)):
        x1, y1 = points[i]
        x2, y2 = points[(i + 1) % len(points)]

        player_line(
            x1,
            y1,
            x2,
            y2,
        )

    # Circular detail also follows scaling.
    hx, hy = transform_local_point(
        0,
        -3,
        player_scale,
        player_angle,
    )

    radius = max(
        1,
        int(round(2 * player_scale)),
    )

    player_circle(
        int(round(hx)),
        int(round(hy)),
        radius,
    )


def draw_player():
    """
    Redraw only the transformed player.
    """

    canvas.delete(
        PLAYER_TAG
    )

    draw_transformed_player_shape()


