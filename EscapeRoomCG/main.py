def rect(x, y, w, h, color=WHITE, tag="world"):
    """
    Rectangle constructed using four DDA lines.
    """

    dda(x, y, x + w, y, color, tag)
    dda(x + w, y, x + w, y + h, color, tag)
    dda(x + w, y + h, x, y + h, color, tag)
    dda(x, y + h, x, y, color, tag)


