# ============================================================

def rotate_player(delta):
    """Rotate the player around its own center."""
    global player_angle

    player_angle = (
        player_angle + delta
    ) % 360

    draw_player()


def scale_player(factor):
    """Scale the player uniformly while keeping a safe range."""
    global player_scale

    player_scale *= factor

    # Keep the player reasonably visible.
    player_scale = max(
        0.5,
        min(2.0, player_scale),
    )

    draw_player()


# ============================================================
# COLLISION
# ============================================================

def player_collides(x, y):

    half = PLAYER_SIZE / 2

    left = x - half
    right = x + half

    top = y - half
    bottom = y + half

    # Current Room 1 obstacles.
    obstacles = [

        # Reception desk.
        (106, 100, 108, 31),

        # Table.
        (120, 186, 120, 44),

        # Storage crate.
        (305, 190, 30, 30),

        # Filing cabinet.
        (320, 67, 29, 32),

        # Notice board.
        (40, 151, 40, 74),
    ]

    for ox, oy, ow, oh in obstacles:

        if (
            right > ox
            and left < ox + ow
            and bottom > oy
            and top < oy + oh
        ):
            return True

    return False


# ============================================================
# TRANSLATION MATRIX
# ============================================================

def translation_matrix(tx, ty):
    """
    Homogeneous 2D translation matrix:

        [ 1   0   tx ]
    T = [ 0   1   ty ]
        [ 0   0    1 ]
    """

    return [
        [1, 0, tx],
        [0, 1, ty],
        [0, 0, 1],
    ]


def translate_point(x, y, tx, ty):
    """
    Apply the translation:

        P' = T * P
    """

    T = translation_matrix(
        tx,
        ty,
    )

    new_x = (
        T[0][0] * x
        + T[0][1] * y
        + T[0][2]
    )

    new_y = (
        T[1][0] * x
        + T[1][1] * y
        + T[1][2]
    )

    return new_x, new_y


# ============================================================
# PLAYER MOVEMENT
# ============================================================

def move_player(dx, dy):

    global player_x
    global player_y

    # Apply 2D translation.
    new_x, new_y = translate_point(
        player_x,
        player_y,
        dx,
        dy,
    )

    # Keep the player inside the room.
    new_x = max(
        PLAYER_MIN_X,
        min(
            PLAYER_MAX_X,
            new_x,
        )
    )

    new_y = max(
        PLAYER_MIN_Y,
        min(
            PLAYER_MAX_Y,
            new_y,
        )
    )

    # Commit translation only if there is no collision.
    if not player_collides(
        new_x,
        new_y,
    ):

        player_x = new_x
        player_y = new_y

        # Only redraw the player.
        draw_player()


