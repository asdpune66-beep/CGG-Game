# PIXEL PLOTTER
# ============================================================

def plot(x, y, color=WHITE, tag="world"):
    """
    Plot one logical pixel.

    Tkinter is only being used to display the individual
    pixels generated by our algorithms.
    """

    x = int(round(x))
    y = int(round(y))

    canvas.create_rectangle(
        x * PIXEL,
        y * PIXEL,
        x * PIXEL + PIXEL,
        y * PIXEL + PIXEL,
        fill=color,
        outline=color,
        tags=tag,
    )


# ============================================================
# DDA LINE DRAWING ALGORITHM
# ============================================================

def dda(x1, y1, x2, y2, color=WHITE, tag="world"):
    """
    Digital Differential Analyzer (DDA) line algorithm.
    """

    dx = x2 - x1
    dy = y2 - y1

    steps = max(abs(dx), abs(dy))

    if steps == 0:
        plot(x1, y1, color, tag)
        return

    x_inc = dx / steps
    y_inc = dy / steps

    x = x1
    y = y1

    # int(round(...)) is important because transformations
    # can produce floating-point coordinates.
    for _ in range(int(round(steps)) + 1):
        plot(x, y, color, tag)

        x += x_inc
        y += y_inc


# ============================================================
# MIDPOINT CIRCLE DRAWING ALGORITHM
# ============================================================

def midpoint_circle(cx, cy, radius, color=WHITE, tag="world"):
    """
    Midpoint Circle Drawing Algorithm using 8-way symmetry.
    """

    x = 0
    y = radius

    # Initial decision parameter.
    p = 1 - radius

    def plot_symmetric_points(px, py):
        points = (
            (cx + px, cy + py),
            (cx - px, cy + py),
            (cx + px, cy - py),
            (cx - px, cy - py),

            (cx + py, cy + px),
            (cx - py, cy + px),
            (cx + py, cy - px),
            (cx - py, cy - px),
        )

        for qx, qy in points:
            plot(qx, qy, color, tag)

    plot_symmetric_points(x, y)

    while x < y:

        x += 1

        if p < 0:
            p += 2 * x + 1

        else:
            y -= 1
            p += 2 * (x - y) + 1

        plot_symmetric_points(x, y)


def filled_circle(cx, cy, radius, color, tag="world"):
    """
    Filled-looking circle constructed using concentric
    Midpoint Circle outlines.
    """

    for r in range(radius, 0, -1):
        midpoint_circle(cx, cy, r, color, tag)


